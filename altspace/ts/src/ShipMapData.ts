// Translated from the upstream Assets/Scripts/ShipMapData.cs: the map's rectangles and the walkable test.
//
// Upstream does this arithmetic in C# `float`. Every step here goes through Math.fround at the same points, so the
// booleans agree with the upstream code exactly (checked by the golden vectors, test/golden.test.ts).

import { Vector2 } from "../portkit/src/index.ts";

export const f = Math.fround;

/** UnityEngine.Rect: position and size in float; Contains is inclusive at the minimum and exclusive at the maximum. */
export class Rect {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
  constructor(x: number, y: number, width: number, height: number) {
    this.x = f(x);
    this.y = f(y);
    this.width = f(width);
    this.height = f(height);
  }
  get xMin(): number { return this.x; }
  get yMin(): number { return this.y; }
  get xMax(): number { return f(this.x + this.width); }
  get yMax(): number { return f(this.y + this.height); }
  get center(): Vector2 { return new Vector2(f(this.x + f(this.width / 2)), f(this.y + f(this.height / 2))); }
  Contains(p: Vector2): boolean {
    return p.x >= this.xMin && p.x < this.xMax && p.y >= this.yMin && p.y < this.yMax;
  }
  static fromArray(a: readonly number[]): Rect {
    return new Rect(a[0]!, a[1]!, a[2]!, a[3]!);
  }
}

/** Mathf.Clamp, Min, Max on floats. */
const clampF = (v: number, lo: number, hi: number) => (v < lo ? lo : v > hi ? hi : v);

/** ShipMapGeometry */
export const ShipMapGeometry = {
  WalkableEdgeInset: f(0.015),

  Inflate(rect: Rect, amount: number): Rect {
    const a = f(amount);
    return new Rect(f(rect.xMin - a), f(rect.yMin - a), f(rect.width + f(a * 2)), f(rect.height + f(a * 2)));
  },

  Inset(rect: Rect, amount: number): Rect {
    const clamped = clampF(f(amount), 0, f(Math.min(rect.width, rect.height) * f(0.45)));
    return new Rect(f(rect.xMin + clamped), f(rect.yMin + clamped), f(rect.width - f(clamped * 2)), f(rect.height - f(clamped * 2)));
  },

  /** The inset the walkable test uses for a body of `radius`: min(0.015, radius x 0.1). */
  InsetFor(radius: number): number {
    return Math.min(ShipMapGeometry.WalkableEdgeInset, f(Math.max(0, f(radius)) * f(0.1)));
  },
};

